/* 海平面月均溫：參考站反距離加權（距離以公里計） */
function seaTemp(lon, lat, m){
  var s = 0, w = 0;
  CM.STATIONS.forEach(function(st){
    var dx = (lon - st.at[0]) * 101.7, dy = (lat - st.at[1]) * 111, d2 = dx * dx + dy * dy + 25, k = 1 / (d2 * d2);
    s += st.t[m - 1] * k; w += k;
  });
  return s / w;
}
